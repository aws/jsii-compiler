import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import * as log4js from 'log4js';
import * as ts from 'typescript';

import { makeProjectInfo } from './compiler-project';
import * as findUtils from '../src/common/find-utils';
import { Compiler } from '../src/compiler';
import * as utils from '../src/utils';

// Make the typescript module's properties configurable so jest.spyOn works.
// TS 6.0 exports non-configurable properties that cannot be spied on directly.
jest.mock('typescript', () => {
  const actual = jest.requireActual('typescript');
  return { __esModule: true, ...actual };
});

let sourceDir: string;

beforeEach(() => {
  sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-config-'));
  writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');
  writeFileSync(join(sourceDir, 'README.md'), '# Test Package');
});

afterEach(() => {
  jest.restoreAllMocks();
  rmSync(sourceDir, { force: true, recursive: true });
});

describe('Compiler configuration', () => {
  test('rejects "generateTypeScriptConfig" together with "typeScriptConfig"', () => {
    expect(
      () =>
        new Compiler({
          projectInfo: makeProjectInfo(sourceDir, 'index.d.ts'),
          generateTypeScriptConfig: 'tsconfig.jsii.json',
          typeScriptConfig: 'tsconfig.dev.json',
        }),
    ).toThrow('Cannot use `generateTypeScriptConfig` and `typeScriptConfig` together. Provide only one of them.');
  });

  test('refuses to overwrite a tsconfig that was not generated by jsii', () => {
    writeFileSync(join(sourceDir, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true } }));
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    expect(() => compiler.emit()).toThrow(
      /file that was not generated by jsii is in .*Aborting instead of overwriting/,
    );
  });

  test('fails when the user-provided tsconfig cannot be read', () => {
    const logDiagnostic = jest.spyOn(utils, 'logDiagnostic').mockImplementation(() => undefined);
    writeFileSync(join(sourceDir, 'tsconfig.dev.json'), '{ this is not json');

    expect(
      () =>
        new Compiler({
          projectInfo: makeProjectInfo(sourceDir, 'index.d.ts'),
          typeScriptConfig: 'tsconfig.dev.json',
        }),
    ).toThrow(`Failed to load tsconfig at ${join(sourceDir, 'tsconfig.dev.json')}`);
    expect(logDiagnostic).toHaveBeenCalledTimes(1);
  });

  test('fails when the TypeScript compiler host has no default library location', () => {
    const createHost = ts.createIncrementalCompilerHost;
    jest.spyOn(ts, 'createIncrementalCompilerHost').mockImplementation((...args) => {
      const host = createHost(...args);
      return { ...host, getDefaultLibLocation: undefined };
    });
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    expect(() => compiler.emit()).toThrow('No default library location was found on the TypeScript compiler host!');
  });

  test('"watch" fails when the TypeScript watch host has no default library location', async () => {
    const createHost = ts.createWatchCompilerHost as (...args: any[]) => ts.WatchCompilerHostOfConfigFile<any>;
    jest.spyOn(ts, 'createWatchCompilerHost').mockImplementation(((...args: any[]) => ({
      ...createHost(...args),
      getDefaultLibLocation: undefined,
    })) as any);
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    await expect(compiler.watch()).rejects.toThrow(
      'No default library location was found on the TypeScript compiler host!',
    );
  });

  test('an empty "lib" list does not add any library files to the program', () => {
    writeFileSync(
      join(sourceDir, 'tsconfig.dev.json'),
      JSON.stringify({ compilerOptions: { lib: [], module: 'node16', target: 'es2023', noLib: true } }),
    );
    const createIncrementalProgram = jest.spyOn(ts, 'createIncrementalProgram');
    const compiler = new Compiler({
      projectInfo: makeProjectInfo(sourceDir, 'index.d.ts'),
      typeScriptConfig: 'tsconfig.dev.json',
    });

    compiler.emit();

    expect(createIncrementalProgram).toHaveBeenCalledWith(
      expect.objectContaining({ rootNames: [expect.stringMatching(/index\.ts$/)] }),
    );
  });

  test('fails when no default library directory is available for the "lib" setting', () => {
    const createHost = ts.createIncrementalCompilerHost;
    jest.spyOn(ts, 'createIncrementalCompilerHost').mockImplementation((...args) => {
      const host = createHost(...args);
      return { ...host, getDefaultLibLocation: () => '' };
    });
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    expect(() => compiler.emit()).toThrow(/Compiler host doesn't have a default library directory available for/);
  });

  test('fails to find the source files when the compiler host cannot read directories', () => {
    const createHost = ts.createIncrementalCompilerHost;
    jest.spyOn(ts, 'createIncrementalCompilerHost').mockImplementation((...args) => {
      const host = createHost(...args);
      return { ...host, readDirectory: undefined };
    });
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    expect(() => compiler.emit()).toThrow("'CompilerHost.readDirectory' must be implemented");
  });

  test('reports an error when the TypeScript output cannot be written', () => {
    // A directory where the compiler wants to write "index.js" makes the emit fail.
    mkdirSync(join(sourceDir, 'index.js'));
    const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

    const result = compiler.emit();

    expect(result.diagnostics).toContainEqual(
      expect.objectContaining({ category: ts.DiagnosticCategory.Error, code: 5033 }),
    );
  });

  describe('"watch" mode', () => {
    test('logs jsii diagnostics of each compilation', async () => {
      const logDiagnostic = jest.spyOn(utils, 'logDiagnostic').mockImplementation(() => undefined);
      jest.spyOn(console, 'log').mockImplementation(() => undefined);
      rmSync(join(sourceDir, 'README.md'));
      const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });

      let compiled!: (result: ts.EmitResult) => void;
      const firstCompilation = new Promise<ts.EmitResult>((resolve) => {
        compiled = resolve;
      });
      const watch = await compiler.watch({
        nonBlocking: true,
        reportDiagnostics: () => undefined,
        reportWatchStatus: () => undefined,
        compilationComplete: (emitResult) => compiled(emitResult),
      });
      try {
        expect((await firstCompilation).emitSkipped).toBe(false);
      } finally {
        watch.close();
      }

      expect(logDiagnostic).toHaveBeenCalledWith(
        expect.objectContaining({ jsiiCode: 3 }), // missing README
        sourceDir,
      );
    }, 25_000);

    test('in blocking mode, never resolves', async () => {
      const watch = { close: jest.fn() } as unknown as ts.Watch<ts.BuilderProgram>;
      jest.spyOn(ts, 'createWatchProgram').mockReturnValue(watch as any);
      const compiler = new Compiler({ projectInfo: makeProjectInfo(sourceDir, 'index.d.ts') });
      const never = Symbol('never resolved');

      const outcome = await Promise.race([
        compiler.watch(),
        new Promise((resolve) => setTimeout(() => resolve(never), 100)),
      ]);

      expect(outcome).toBe(never);
    });
  });
});

describe('Compiler project references', () => {
  const warn = () => jest.spyOn(Object.getPrototypeOf(log4js.getLogger('jsii/compiler')), 'warn');

  /**
   * Creates `node_modules/<name>` as a symlink to a package with the given tsconfig located at `location`.
   */
  function installPeer(name: string, tsconfig: object | undefined, location: string, link = true) {
    const peerDir = join(sourceDir, location);
    mkdirSync(peerDir, { recursive: true });
    writeFileSync(join(peerDir, 'package.json'), JSON.stringify({ name, version: '1.0.0', main: 'index.js' }));
    writeFileSync(join(peerDir, 'index.js'), '');
    if (tsconfig) {
      writeFileSync(join(peerDir, 'tsconfig.json'), JSON.stringify(tsconfig));
    }
    if (link) {
      mkdirSync(join(sourceDir, 'node_modules'), { recursive: true });
      symlinkSync(peerDir, join(sourceDir, 'node_modules', name), 'dir');
    }
  }

  function compileWithDependencies(dependencies: Record<string, string>) {
    const compiler = new Compiler({
      projectInfo: makeProjectInfo(sourceDir, 'index.d.ts', { packageJson: { dependencies } }),
      projectReferences: true,
    });
    compiler.emit();
    return JSON.parse(readFileSync(join(sourceDir, 'tsconfig.json'), 'utf-8'));
  }

  test('adds a reference to a composite monorepo peer', () => {
    installPeer('peer', { compilerOptions: { composite: true } }, 'packages/peer');

    expect(compileWithDependencies({ peer: '*' }).references).toEqual([{ path: join('packages', 'peer') }]);
  });

  test('does not reference a monorepo peer that is not composite', () => {
    const logger = warn();
    installPeer('peer', { compilerOptions: {} }, 'packages/peer');

    expect(compileWithDependencies({ peer: '*' }).references).toEqual([]);
    expect(logger).not.toHaveBeenCalledWith(
      expect.stringContaining('not a composite TypeScript package'),
      expect.anything(),
    );
  });

  test('warns about a non-composite peer when its path contains "node_modules" as part of a directory name', () => {
    const logger = warn();
    installPeer('peer', { compilerOptions: {} }, 'my-node_modules-packages/peer');

    expect(compileWithDependencies({ peer: '*' }).references).toEqual([]);
    expect(logger).toHaveBeenCalledWith(
      '%s: not a composite TypeScript package, but it probably should be',
      expect.stringContaining('my-node_modules-packages'),
    );
  });

  test('ignores dependencies installed in node_modules (not monorepo peers)', () => {
    installPeer('installed', { compilerOptions: { composite: true } }, 'node_modules/installed', false);

    expect(compileWithDependencies({ installed: '*' }).references).toEqual([]);
  });

  test('ignores dependencies without a tsconfig.json', () => {
    installPeer('no-tsconfig', undefined, 'packages/no-tsconfig');

    expect(compileWithDependencies({ 'no-tsconfig': '*' }).references).toEqual([]);
  });

  test('ignores dependencies that are Node.js built-in modules', () => {
    const findDependencyDirectory = jest.spyOn(findUtils, 'findDependencyDirectory');

    expect(compileWithDependencies({ punycode: '*' }).references).toEqual([]);
    expect(findDependencyDirectory).not.toHaveBeenCalled();
  });

  test.each(['MODULE_NOT_FOUND', 'ERR_PACKAGE_PATH_NOT_EXPORTED'])('ignores dependencies that fail with %s', (code) => {
    jest.spyOn(findUtils, 'findDependencyDirectory').mockImplementation(() => {
      throw Object.assign(new Error('cannot be resolved'), { code });
    });

    expect(compileWithDependencies({ '@types/node': '*' }).references).toEqual([]);
  });

  test('propagates other errors when looking for dependencies', () => {
    jest.spyOn(findUtils, 'findDependencyDirectory').mockImplementation(() => {
      throw new Error('boom');
    });

    expect(() => compileWithDependencies({ unexpected: '*' })).toThrow('boom');
  });
});
