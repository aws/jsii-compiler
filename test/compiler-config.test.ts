import { mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as log4js from 'log4js';
import { compileJsiiForTest, TestWorkspace } from '../src';

/**
 * These tests compile small projects with the configuration options of the compiler, through the `compileJsiiForTest`
 * helper, and check the outcome: the emitted files, the diagnostics, the error a user gets.
 */

const SOURCE = 'export class MarkerA {}';

describe('Compiler configuration', () => {
  test('rejects "generateTypeScriptConfig" together with "typeScriptConfig"', () => {
    expect(() =>
      compileJsiiForTest(SOURCE, undefined, {
        generateTypeScriptConfig: 'tsconfig.jsii.json',
        typeScriptConfig: 'tsconfig.dev.json',
      }),
    ).toThrow('Cannot use `generateTypeScriptConfig` and `typeScriptConfig` together. Provide only one of them.');
  });

  test('refuses to overwrite a tsconfig that was not generated by jsii', () => {
    expect(() =>
      compileJsiiForTest({
        'index.ts': SOURCE,
        'tsconfig.json': JSON.stringify({ compilerOptions: { strict: true } }),
      }),
    ).toThrow(/file that was not generated by jsii is in .*Aborting instead of overwriting/);
  });

  test('fails when the user-provided tsconfig cannot be read', () => {
    expect(() =>
      compileJsiiForTest({ 'index.ts': SOURCE, 'tsconfig.dev.json': '{ this is not json' }, undefined, {
        typeScriptConfig: 'tsconfig.dev.json',
      }),
    ).toThrow(/Failed to load tsconfig at .*tsconfig\.dev\.json/);
  });

  test('fails when the user-provided tsconfig does not pass the validation', () => {
    expect(() =>
      compileJsiiForTest(
        {
          'index.ts': SOURCE,
          'tsconfig.dev.json': JSON.stringify({ compilerOptions: { target: 'es2023', module: 'node16' } }),
        },
        undefined,
        { typeScriptConfig: 'tsconfig.dev.json', validateTypeScriptConfig: 'strict' as any },
      ),
    ).toThrow('Failed validation of tsconfig "compilerOptions" in "tsconfig.dev.json" against rule set "strict"!');
  });

  test('an empty "lib" list does not add any library files to the program', () => {
    const result = compileJsiiForTest(
      {
        'index.ts': SOURCE,
        'tsconfig.dev.json': JSON.stringify({
          compilerOptions: { lib: [], module: 'node16', target: 'es2023', noLib: true },
        }),
      },
      { captureDiagnostics: true },
      { typeScriptConfig: 'tsconfig.dev.json' },
    );

    // Without library files, the global types (such as "Array") do not exist.
    expect(result.type).toBe('failure');
    expect(result.diagnostics).toContainEqual(
      expect.objectContaining({ code: 2318, messageText: "Cannot find global type 'Array'." }),
    );
  });

  // @TODO(ts7): the TypeScript 7 compiler does not report TS5033 (fix on branch emit-write-errors)
  test.skip('reports an error when the TypeScript output cannot be written', () => {
    // A directory where the compiler wants to write "index.js" makes the emit fail.
    const result = compileJsiiForTest({ 'index.ts': SOURCE, 'index.js/keep': '' }, { captureDiagnostics: true });

    expect(result.type).toBe('failure');
    expect(result.diagnostics).toContainEqual(expect.objectContaining({ code: 5033 }));
  });
});

describe('Compiler project references', () => {
  const recording = log4js.recording();

  beforeEach(() => {
    log4js.configure({
      appenders: { recording: { type: 'recording' } },
      categories: { default: { appenders: ['recording'], level: 'trace' } },
    });
  });

  afterEach(() => {
    recording.erase();
    log4js.configure({
      appenders: { console: { type: 'console' } },
      categories: { default: { appenders: ['console'], level: 'off' } },
    });
  });

  const warnings = () =>
    recording
      .replay()
      .filter((event) => event.level.levelStr === 'WARN')
      .map((event) => event.data.join(' '));

  /**
   * Creates the package `name` (a jsii assembly, with a tsconfig if one is given) in `location` of the workspace, and
   * `node_modules/<name>` as a symlink to it when `link` is true.
   */
  function installPeer(ws: TestWorkspace, name: string, tsconfig: object | undefined, location: string, link = true) {
    const peer = compileJsiiForTest('export class Peer {}', { packageJson: { name } });
    const peerDir = join(ws.rootDirectory, location);
    mkdirSync(peerDir, { recursive: true });
    writeFileSync(join(peerDir, 'package.json'), JSON.stringify(peer.packageJson));
    writeFileSync(join(peerDir, '.jsii'), JSON.stringify(peer.assembly));
    writeFileSync(join(peerDir, 'index.js'), '');
    if (tsconfig) {
      writeFileSync(join(peerDir, 'tsconfig.json'), JSON.stringify(tsconfig));
    }
    if (link) {
      mkdirSync(join(ws.rootDirectory, 'node_modules'), { recursive: true });
      symlinkSync(peerDir, join(ws.rootDirectory, 'node_modules', name), 'dir');
    }
    return peerDir;
  }

  /** Compiles a package that depends on `dependencies`, and returns the tsconfig that was generated for it. */
  function compileWithDependencies(ws: TestWorkspace, dependencies: Record<string, string>) {
    compileJsiiForTest(
      SOURCE,
      {
        compilationDirectory: ws.rootDirectory,
        packageJson: { dependencies, peerDependencies: dependencies },
      },
      { projectReferences: true },
    );
    return JSON.parse(readFileSync(join(ws.rootDirectory, 'tsconfig.json'), 'utf-8'));
  }

  test('adds a reference to a composite monorepo peer', () =>
    TestWorkspace.withWorkspace((ws) => {
      installPeer(ws, 'peer', { compilerOptions: { composite: true } }, 'packages/peer');

      expect(compileWithDependencies(ws, { peer: '*' }).references).toEqual([{ path: join('packages', 'peer') }]);
    }));

  test('does not reference a monorepo peer that is not composite', () =>
    TestWorkspace.withWorkspace((ws) => {
      installPeer(ws, 'peer', { compilerOptions: {} }, 'packages/peer');

      expect(compileWithDependencies(ws, { peer: '*' }).references).toEqual([]);
      expect(warnings()).toEqual([]);
    }));

  test('warns about a non-composite peer when its path contains "node_modules" as part of a directory name', () =>
    TestWorkspace.withWorkspace((ws) => {
      installPeer(ws, 'peer', { compilerOptions: {} }, 'my-node_modules-packages/peer');

      expect(compileWithDependencies(ws, { peer: '*' }).references).toEqual([]);
      expect(warnings()).toEqual([expect.stringContaining('my-node_modules-packages')]);
      expect(warnings()[0]).toContain('not a composite TypeScript package, but it probably should be');
    }));

  test('ignores dependencies installed in node_modules (not monorepo peers)', () =>
    TestWorkspace.withWorkspace((ws) => {
      installPeer(ws, 'installed', { compilerOptions: { composite: true } }, 'node_modules/installed', false);

      expect(compileWithDependencies(ws, { installed: '*' }).references).toEqual([]);
    }));

  test('ignores dependencies without a tsconfig.json', () =>
    TestWorkspace.withWorkspace((ws) => {
      installPeer(ws, 'no-tsconfig', undefined, 'packages/no-tsconfig');

      expect(compileWithDependencies(ws, { 'no-tsconfig': '*' }).references).toEqual([]);
    }));

  describe('bundled dependencies that are not jsii packages', () => {
    /** Compiles a package that bundles `name`, which has no jsii assembly, and returns its generated tsconfig. */
    function compileWithBundled(ws: TestWorkspace, name: string) {
      compileJsiiForTest(
        SOURCE,
        {
          compilationDirectory: ws.rootDirectory,
          packageJson: { dependencies: { [name]: '*' }, bundleDependencies: [name] } as any,
        },
        { projectReferences: true },
      );
      return JSON.parse(readFileSync(join(ws.rootDirectory, 'tsconfig.json'), 'utf-8'));
    }

    test('are ignored when they are Node.js built-in modules', () =>
      TestWorkspace.withWorkspace((ws) => {
        expect(compileWithBundled(ws, 'punycode').references).toEqual([]);
      }));

    test('are ignored when they are not installed', () =>
      TestWorkspace.withWorkspace((ws) => {
        expect(compileWithBundled(ws, 'not-installed').references).toEqual([]);
      }));

    test('fail the build when the package.json that is found has another name', () =>
      TestWorkspace.withWorkspace((ws) => {
        const dir = join(ws.rootDirectory, 'node_modules', 'renamed');
        mkdirSync(dir, { recursive: true });
        writeFileSync(
          join(dir, 'package.json'),
          JSON.stringify({ name: 'something-else', version: '1.0.0', main: 'index.js' }),
        );
        writeFileSync(join(dir, 'index.js'), '');

        expect(() => compileWithBundled(ws, 'renamed')).toThrow(/Could not find dependency 'renamed' from/);
      }));

    test('are ignored when they do not export their entry point', () =>
      TestWorkspace.withWorkspace((ws) => {
        const dir = join(ws.rootDirectory, 'node_modules', 'hidden');
        mkdirSync(dir, { recursive: true });
        writeFileSync(
          join(dir, 'package.json'),
          JSON.stringify({ name: 'hidden', version: '1.0.0', exports: { './package.json': './package.json' } }),
        );
        writeFileSync(join(dir, 'index.js'), '');

        expect(compileWithBundled(ws, 'hidden').references).toEqual([]);
      }));
  });

  test('fails when the package.json that matches the dependency cannot be found', () =>
    TestWorkspace.withWorkspace((ws) => {
      const peerDir = installPeer(ws, 'renamed', { compilerOptions: { composite: true } }, 'packages/renamed');
      const packageJson = JSON.parse(readFileSync(join(peerDir, 'package.json'), 'utf-8'));
      writeFileSync(join(peerDir, 'package.json'), JSON.stringify({ ...packageJson, name: 'something-else' }));

      expect(() => compileWithDependencies(ws, { renamed: '*' })).toThrow(/Could not find dependency 'renamed' from/);
    }));
});
