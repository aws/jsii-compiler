// Make the typescript module's properties configurable so jest.spyOn works.
// TS 6.0 exports non-configurable properties that cannot be spied on directly.
jest.mock('typescript', () => {
  const actual = jest.requireActual('typescript');
  // Spread into a fresh object to make all properties writable/configurable
  return { __esModule: true, ...actual };
});

beforeEach(() => {
  jest.restoreAllMocks();
});

describe(Compiler, () => {
  describe('generated tsconfig', () => {
    test('default is tsconfig.json', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-watch-mode-'));

      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
      });

      compiler.emit();

      expect(JSON.parse(readFileSync(join(sourceDir, 'tsconfig.json'), 'utf-8'))).toEqual(expectedTypeScriptConfig());
    });

    test('file name can be customized', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-watch-mode-'));

      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
        generateTypeScriptConfig: 'tsconfig.jsii.json',
      });

      compiler.emit();

      expect(JSON.parse(readFileSync(join(sourceDir, 'tsconfig.jsii.json'), 'utf-8'))).toEqual(
        expectedTypeScriptConfig(),
      );
    });

    test('overwrites existing tsconfig.json with JSONC comments', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-jsonc-'));

      // Simulate a projen-generated tsconfig.json with a leading comment
      writeFileSync(
        join(sourceDir, 'tsconfig.json'),
        '// ~~ Generated by projen. To modify, edit .projenrc.ts\n' +
          JSON.stringify({ _generated_by_jsii_: 'placeholder', compilerOptions: {} }, null, 2),
      );

      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
      });

      compiler.emit();

      expect(JSON.parse(readFileSync(join(sourceDir, 'tsconfig.json'), 'utf-8'))).toEqual(expectedTypeScriptConfig());
    });

    test('generated tsconfig passed validation', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-watch-mode-'));

      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
      });

      compiler.emit();

      // read generated config
      const tsconfig = JSON.parse(readFileSync(join(sourceDir, 'tsconfig.json'), 'utf-8'));

      // set up the tsconfig validator with rules for the generated file
      const validator = new TypeScriptConfigValidator(TypeScriptConfigValidationRuleSet.GENERATED);

      expect(() => validator.validate(tsconfig)).not.toThrow();
    });

    test('absolute rootDir is emitted as a relative tscRootDir in the assembly', () => {
      const outDir = 'jsii-outdir';
      const rootDir = 'jsii-rootdir';
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));
      mkdirSync(join(sourceDir, rootDir), { recursive: true });

      try {
        writeFileSync(join(sourceDir, rootDir, 'index.ts'), 'export class MarkerA {}');
        writeFileSync(join(sourceDir, rootDir, 'README.md'), '# Test Package');

        const compiler = new Compiler({
          projectInfo: {
            ..._makeProjectInfo(sourceDir, join(outDir, 'index.d.ts')),
            tsc: {
              outDir,
              // Pass an ABSOLUTE rootDir, as happens in real out-of-source
              // builds. The assembly must still record it relative to the
              // package root, otherwise the absolute (machine-specific) path
              // leaks into `metadata.tscRootDir` and breaks the assembly
              // fingerprint/reproducibility check for downstream consumers.
              rootDir: join(sourceDir, rootDir),
            },
          },
          failOnWarnings: true,
          projectReferences: false,
        });

        compiler.emit();

        const assembly = loadAssemblyFromPath(sourceDir);
        expect(assembly.metadata).toEqual(
          expect.objectContaining({
            tscRootDir: rootDir,
          }),
        );
        expect(isAbsolute(assembly.metadata!.tscRootDir as string)).toBe(false);
      } finally {
        rmSync(sourceDir, { force: true, recursive: true });
      }
    });

    test('rootDir and outDir are added to assembly', () => {
      const outDir = 'jsii-outdir';
      const rootDir = 'jsii-rootdir';
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));
      mkdirSync(join(sourceDir, rootDir), { recursive: true });

      try {
        writeFileSync(join(sourceDir, rootDir, 'index.ts'), 'export class MarkerA {}');
        // Intentionally using lower case name - it should be case-insensitive
        writeFileSync(join(sourceDir, rootDir, 'readme.md'), '# Test Package');

        const compiler = new Compiler({
          projectInfo: {
            ..._makeProjectInfo(sourceDir, join(outDir, 'index.d.ts')),
            tsc: {
              outDir,
              rootDir,
            },
          },
          failOnWarnings: true,
          projectReferences: false,
        });

        compiler.emit();

        const assembly = loadAssemblyFromPath(sourceDir);
        expect(assembly.metadata).toEqual(
          expect.objectContaining({
            tscRootDir: rootDir,
            tscOutDir: outDir,
          }),
        );
      } finally {
        rmSync(sourceDir, { force: true, recursive: true });
      }
    });

    test.each([
      { sources: '.', types: 'index.d.ts', rootDir: undefined, advice: `Set it to "${join('dist', 'index.d.ts')}"` },
      { sources: 'lib', types: 'index.d.ts', rootDir: 'lib', advice: 'Point "types" and "main" at the compiled files' },
    ])('reports "types" outside of outDir (sources in $sources)', ({ sources, types, rootDir, advice }) => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));
      mkdirSync(join(sourceDir, sources), { recursive: true });

      try {
        writeFileSync(join(sourceDir, sources, 'index.ts'), 'export class MarkerA {}');
        writeFileSync(join(sourceDir, 'README.md'), '# Test Package');

        const compiler = new Compiler({
          projectInfo: {
            ..._makeProjectInfo(sourceDir, types),
            tsc: { outDir: 'dist', rootDir },
          },
          projectReferences: false,
        });

        const result = compiler.emit();

        expect(result.emitSkipped).toBe(true);
        const jsiiDiagnostics = result.diagnostics.filter(JsiiDiagnostic.isJsiiDiagnostic);
        // Report the misplaced "types" instead of a missing entry point next to the outDir.
        expect(jsiiDiagnostics.map((diag) => diag.jsiiCode)).toEqual([8]);
        expect(String(jsiiDiagnostics[0].messageText)).toContain(advice);
      } finally {
        rmSync(sourceDir, { force: true, recursive: true });
      }
    });

    test('emits declaration map when feature is enabled', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));

      try {
        writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');

        const compiler = new Compiler({
          projectInfo: {
            ..._makeProjectInfo(sourceDir, 'index.d.ts'),
            tsc: {
              declarationMap: true,
            },
          },
          generateTypeScriptConfig: 'tsconfig.jsii.json',
        });

        compiler.emit();

        expect(() => {
          readFileSync(join(sourceDir, 'index.d.ts.map'), 'utf-8');
        }).not.toThrow();
      } finally {
        rmSync(sourceDir, { force: true, recursive: true });
      }
    });

    describe('project references', () => {
      let lock: Lock | undefined;

      beforeAll(async () => {
        lock = await Lock.acquire();
      }, 120_000);

      afterAll(async () => {
        await lock?.release();
        lock = undefined;
      }, 120_000);

      test('can resolve project references', async () => {
        const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-project-refs'));

        // link the composite package
        const fixture = '@fixtures/jsii-composite';
        const fixtureLocation = compile(lock!, fixture, false);
        const linkLocation = join(sourceDir, 'node_modules', fixture);
        mkdirSync(dirname(linkLocation), { recursive: true });
        symlinkSync(fixtureLocation, linkLocation, 'dir');

        // Add some files to the parent project
        writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');
        writeFileSync(join(sourceDir, 'README.md'), '# Test Package');

        const compiler = new Compiler({
          projectInfo: {
            ..._makeProjectInfo(sourceDir, 'index.d.ts'),
            packageJson: {
              devDependencies: {
                '@fixtures/jsii-composite': '*',
              },
            },
          },
          projectReferences: true,
        });

        compiler.emit();

        expect(JSON.parse(readFileSync(join(sourceDir, 'tsconfig.json'), 'utf-8'))).toMatchObject({
          compilerOptions: {
            composite: true,
          },
          references: [
            {
              path: expect.stringMatching('fixtures/@fixtures/jsii-composite'),
            },
          ],
        });
      }, 120_000);
    });
  });

  describe('user-provided tsconfig', () => {
    let sourceDir: string;
    const tsconfigPath = 'tsconfig.dev.json';
    beforeEach(() => {
      sourceDir = mkdtempSync(join(tmpdir(), 'jsii-compiler-user-tsconfig-'));
    });

    afterEach(() => {
      rmSync(sourceDir, { force: true, recursive: true });
    });

    test('will use user-provided config', () => {
      writeFileSync(join(sourceDir, tsconfigPath), JSON.stringify(tsconfigForNode18Strict(), null, 2));

      writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');
      writeFileSync(join(sourceDir, 'README.md'), '# Test Package');
      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
        typeScriptConfig: tsconfigPath,
      });

      const result = compiler.emit();
      expect(result.diagnostics).toEqual([]);
      expect(result.emitSkipped).toBe(false);
    });

    test('use user-provided config uses include and exclude', () => {
      mkdirSync(join(sourceDir, 'sub'));
      writeFileSync(
        join(sourceDir, tsconfigPath),
        JSON.stringify(
          {
            compilerOptions: {
              lib: ['es2023'],
              module: 'node16',
              target: 'es2023',
              noImplicitAny: true,
            },
            include: ['**/*.ts'],
            exclude: ['sub/**'],
          },
          null,
          2,
        ),
      );

      writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');
      writeFileSync(join(sourceDir, 'README.md'), '# Test Package');

      // file with an implicit any that fails against the local config if not excluded
      writeFileSync(join(sourceDir, 'sub', 'index.ts'), 'export class MarkerB { constructor(public foobar) {} }');

      const compiler = new Compiler({
        projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
        typeScriptConfig: tsconfigPath,
      });

      const result = compiler.emit();
      expect(result.diagnostics).toEqual([]);
      expect(result.emitSkipped).toBe(false);
    });
  });

  describe('package name', () => {
    test.each([
      { desc: 'a class', name: '@foo/example.jsii-dot-error', source: 'export class Foo {}' },
      { desc: 'a dot in the scope', name: '@foo.bar/baz', source: 'export class Foo {}' },
      {
        desc: 'a subclass',
        name: '@foo/example.jsii-dot-error',
        source: 'export class Base {}\nexport class Derived extends Base {}',
      },
      {
        desc: 'a class that implements an extended interface',
        name: '@foo/example.jsii-dot-error',
        source:
          'export interface IA { readonly a: string; }\nexport interface IB extends IA { readonly b: string; }\n' +
          "export class Foo implements IB { public readonly a = ''; public readonly b = ''; }",
      },
      {
        desc: 'a class that uses an interface',
        name: '@foo/example.jsii-dot-error',
        source:
          'export interface Props { readonly name: string; }\nexport class Foo { public constructor(_props: Props) {} }',
      },
    ])('reports a package name that contains a dot ($desc)', ({ name, source }) => {
      const result = compileJsiiForTest(source, { captureDiagnostics: true, projectInfo: { name } });

      // Only the package name is reported, not the types that jsii looked up by name.
      const errors = result.diagnostics
        .filter(JsiiDiagnostic.isJsiiDiagnostic)
        .filter((diag) => diag.category === DiagnosticCategory.Error);
      expect(errors.map((diag) => diag.jsiiCode)).toEqual([9]);
      expect(String(errors[0].messageText)).toContain(`${JSON.stringify(name)} contains a "."`);
    });

    test('does not report a package name without a dot', () => {
      const result = compileJsiiForTest('export class Foo {}', {
        captureDiagnostics: true,
        projectInfo: { name: '@foo/example-jsii-dot-error' },
      });

      expect(result.diagnostics.filter(JsiiDiagnostic.isJsiiDiagnostic).map((diag) => diag.jsiiCode)).not.toContain(9);
    });
  });

  describe('compressed assembly option', () => {
    test('creates a gzipped assembly file', () => {
      const sourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));

      try {
        writeFileSync(join(sourceDir, 'index.ts'), 'export class MarkerA {}');

        const compiler = new Compiler({
          projectInfo: _makeProjectInfo(sourceDir, 'index.d.ts'),
          compressAssembly: true,
        });

        compiler.emit();

        expect(existsSync(join(sourceDir, SPEC_FILE_NAME_COMPRESSED))).toBeTruthy();
      } finally {
        rmSync(sourceDir, { force: true, recursive: true });
      }
    });

    test('creates file equivalent to uncompressed file', () => {
      const uncompressedSourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir'));
      const compressedSourceDir = mkdtempSync(join(tmpdir(), 'jsii-tmpdir-2'));

      try {
        const fileContents = 'export class MarkerA {}';
        writeFileSync(join(uncompressedSourceDir, 'index.ts'), fileContents);
        writeFileSync(join(compressedSourceDir, 'index.ts'), fileContents);

        const uncompressedJsiiCompiler = new Compiler({
          projectInfo: _makeProjectInfo(uncompressedSourceDir, 'index.d.ts'),
        });
        const compressedJsiiCompiler = new Compiler({
          projectInfo: _makeProjectInfo(compressedSourceDir, 'index.d.ts'),
          compressAssembly: true,
        });

        uncompressedJsiiCompiler.emit();
        compressedJsiiCompiler.emit();

        // The files we expect are there
        expect(existsSync(join(uncompressedSourceDir, SPEC_FILE_NAME))).toBeTruthy();
        expect(existsSync(join(compressedSourceDir, SPEC_FILE_NAME_COMPRESSED))).toBeTruthy();

        const uncompressedJsii = loadAssemblyFromPath(uncompressedSourceDir);
        const compressedJsii = loadAssemblyFromPath(compressedSourceDir);

        expect(compressedJsii).toEqual(uncompressedJsii);
      } finally {
        rmSync(uncompressedSourceDir, { force: true, recursive: true });
        rmSync(compressedSourceDir, { force: true, recursive: true });
      }
    });
  });
});

const ARRAY_OF_STRING = {
  collection: {
    elementtype: { primitive: PrimitiveType.String },
    kind: CollectionKind.Array,
  },
};

describe('readonly arrays', () => {
  test('mutable string[] control compiles as an array collection', () => {
    const result = compileJsiiForTest(`
      export interface Props {
        readonly values: string[];
      }
    `);

    expect(result.assembly.types!['testpkg.Props']).toEqual(
      expect.objectContaining({
        datatype: true,
        kind: 'interface',
        properties: [
          expect.objectContaining({
            immutable: true,
            name: 'values',
            type: ARRAY_OF_STRING,
          }),
        ],
      }),
    );
    expect(result.files['index.d.ts']).toContain('readonly values: string[]');
  });

  test('readonly string[] compiles as an array collection', () => {
    const result = compileJsiiForTest(`
      export interface Props {
        readonly values: readonly string[];
      }
    `);

    expect(result.assembly.types!['testpkg.Props']).toEqual(
      expect.objectContaining({
        datatype: true,
        kind: 'interface',
        properties: [
          expect.objectContaining({
            immutable: true,
            name: 'values',
            type: ARRAY_OF_STRING,
          }),
        ],
      }),
    );
    expect(result.files['index.d.ts']).toContain('readonly values: readonly string[]');
  });

  test('ReadonlyArray<string> compiles as an array collection', () => {
    const result = compileJsiiForTest(`
      export interface Props {
        readonly values: ReadonlyArray<string>;
      }
    `);

    expect(result.assembly.types!['testpkg.Props']).toEqual(
      expect.objectContaining({
        datatype: true,
        kind: 'interface',
        properties: [
          expect.objectContaining({
            immutable: true,
            name: 'values',
            type: ARRAY_OF_STRING,
          }),
        ],
      }),
    );
    expect(result.files['index.d.ts']).toContain('readonly values: ReadonlyArray<string>');
  });

  test('readonly arrays recursively validate element types', () => {
    const result = compileJsiiForTest(`
      export interface Item {
        readonly n: number;
      }

      export interface Props {
        readonly items: readonly Item[];
      }
    `);

    expect(result.assembly.types!['testpkg.Props']).toEqual(
      expect.objectContaining({
        properties: [
          expect.objectContaining({
            name: 'items',
            type: {
              collection: {
                elementtype: { fqn: 'testpkg.Item' },
                kind: CollectionKind.Array,
              },
            },
          }),
        ],
      }),
    );
  });

  test('constructor parameter and inferred return value of readonly arrays compile', () => {
    const result = compileJsiiForTest(`
      export interface Props {
        readonly p: readonly string[];
      }

      export class C {
        private s: readonly string[];
        constructor(p: Props) {
          this.s = p.p;
        }
        f() {
          return this.s;
        }
      }
    `);

    expect(result.assembly.types!['testpkg.Props']).toEqual(
      expect.objectContaining({
        properties: [
          expect.objectContaining({
            name: 'p',
            type: ARRAY_OF_STRING,
          }),
        ],
      }),
    );
    expect(result.assembly.types!['testpkg.C']).toEqual(
      expect.objectContaining({
        kind: 'class',
        initializer: expect.objectContaining({
          parameters: [
            expect.objectContaining({
              name: 'p',
              type: { fqn: 'testpkg.Props' },
            }),
          ],
        }),
        methods: [
          expect.objectContaining({
            name: 'f',
            returns: { type: ARRAY_OF_STRING },
          }),
        ],
      }),
    );
    expect(result.files['index.d.ts']).toContain('readonly p: readonly string[]');
    expect(result.files['index.d.ts']).toMatch(/f\(\):\s*readonly string\[\]/);
  });

  test('tuple types remain unsupported', () => {
    expect(
      compileJsiiForErrors(`
        export interface Props {
          readonly pair: [string, number];
        }
      `),
    ).toContainEqual('Tuple types are not supported in jsii APIs. Consider using arrays instead.');
  });

  test('readonly tuple types remain unsupported', () => {
    expect(
      compileJsiiForErrors(`
        export interface Props {
          readonly pair: readonly [string, number];
        }
      `),
    ).toContainEqual('Tuple types are not supported in jsii APIs. Consider using arrays instead.');
  });

  test('user-defined type named ReadonlyArray is not treated as an array', () => {
    const result = compileJsiiForTest(`
      export class ReadonlyArray {
        public readonly marker = true;
      }

      export class Consumer {
        public readonly values: ReadonlyArray = new ReadonlyArray();
      }
    `);

    expect(result.assembly.types!['testpkg.Consumer']).toEqual(
      expect.objectContaining({
        properties: [
          expect.objectContaining({
            name: 'values',
            type: { fqn: 'testpkg.ReadonlyArray' },
          }),
        ],
      }),
    );
    expect(result.files['index.d.ts']).toContain('readonly values: ReadonlyArray');
    expect(result.files['index.d.ts']).not.toContain('readonly values: readonly');
  });
});

function _makeProjectInfo(sourceDir: string, types: string): ProjectInfo {
  return {
    projectRoot: sourceDir,
    description: 'test',
    homepage: 'https://github.com/aws/jsii-compiler',
    packageJson: {},
    types,
    main: types.replace(/(?:\.d)?\.ts(x?)/, '.js$1'),
    name: 'jsii', // That's what package.json would tell if we look up...
    version: '0.0.1',
    jsiiVersionFormat: 'short',
    license: 'Apache-2.0',
    author: { name: 'John Doe', roles: ['author'] },
    repository: { type: 'git', url: 'https://github.com/aws/jsii.git' },
    dependencies: {},
    peerDependencies: {},
    dependencyClosure: [],
    bundleDependencies: {},
    targets: {},
    excludeTypescript: [],
    tsc: {
      // NOTE: these are the default values jsii uses when none are provided in package.json.
      inlineSourceMap: true,
      inlineSources: true,
    },
  };
}

